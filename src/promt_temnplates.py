import json
from src.llm_client import ask_gigachat

def analyze_news_prompt(news_title: str, news_text: str) -> str:
    """
    Конструирует структурированный промпт для определения тематики текста (на основе нового датасета).
    """
    prompt = f"""
Ты — профессиональный ИИ-аналитик. Твоя задача — проанализировать текст и определить, к какой теме (категории) он относится.

Выбери СТРОГО ОДНУ тему из следующего списка:
- Культура
- Библиотека
- Интернет и СМИ
- Политика
- Спорт
- Наука

Выведи результат СТРОГО в формате JSON. Не пиши никаких вводных слов, markdown-разметки или пояснений вне JSON.

### ПРИМЕРЫ:

Входной текст:
Заголовок: "В Москве открылась выставка современного искусства"
Текст: "Сегодня в столичном музее состоялось открытие ежегодной выставки. Художники представили более 100 картин, скульптур и инсталляций. Мероприятие продлится до конца месяца, ожидается участие известных критиков."
Выходной JSON:
{{"topic": "Культура", "reason": "Текст описывает открытие художественной выставки, картины и скульптуры, что напрямую относится к сфере искусства и культуры."}}

Входной текст:
Заголовок: "Библиотека имени Ленина оцифровала редкие рукописи"
Текст: "Крупнейшая библиотека страны завершила проект по сканированию древних манускриптов. Теперь читатели могут получить доступ к архивам через официальный портал. В планах учреждения — создание виртуальных читальных залов."
Выходной JSON:
{{"topic": "Библиотека", "reason": "В тексте упоминается библиотека, сканирование рукописей и создание читальных залов, что характерно для тематики библиотечного дела."}}

### РЕАЛЬНОЕ ЗАДАНИЕ:
Входной текст:
Заголовок: "{news_title}"
Текст: "{news_text}"
Выходной JSON:
"""
    return prompt


if __name__ == "__main__":
    raw_title = "Новый фильм о космосе возглавил прокат"
    raw_text = "Премьера научно-фантастической картины собрала рекордную кассу в первые выходные. Критики отмечают высокий уровень визуальных эффектов и игру главных актеров. Картина рассказывает о путешествии к далеким галактикам и уже получила несколько наград на международных фестивалях."

    print("1. Формируем сложный промпт...")
    final_prompt = analyze_news_prompt(raw_title, raw_text)

    print("2. Отправляем запрос в GigaChat...")
    # Отправляем промпт в нейросеть
    raw_response = ask_gigachat(final_prompt, temperature=0.1)

    print(f"\nСырой ответ от модели: \n{raw_response}\n")

    print("3. Проверяем валидность полученного JSON...")
    try:
        # Очищаем ответ от возможных markdown-тегов (```json ... ```)
        clean_response = raw_response.strip().replace("```json", "").replace("```", "")
        parsed_json = json.loads(clean_response)

        print("Успех! Данные успешно преобразованы в Python dict:")
        print(f"Тема: {parsed_json.get('topic')}")
        print(f"Причина: {parsed_json.get('reason')}")

    except json.JSONDecodeError:
        print("Ошибка: Модель нарушила формат и вернула неверный JSON.")